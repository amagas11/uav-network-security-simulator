import assert from 'node:assert/strict'
import fs from 'node:fs'
import {createJiti} from 'jiti'
const {authFailureReportCount,booleanResult,blockedPacketCount,legitimateHarmResult}=await createJiti(import.meta.url).import('../src/utils/dosPresentation.ts')
const reports=Array.from({length:800},(_,i)=>({report_id:`r${i}`,category:'AUTH_FAILURE'}))
reports.push({category:'DOS'},{category:'SUMMARY'})
assert.equal(authFailureReportCount(true,reports),800)
assert.equal(authFailureReportCount(false,reports),null)
assert.equal(authFailureReportCount(true,undefined),null)
assert.equal(authFailureReportCount(true,[]),0)
assert.equal(authFailureReportCount(true,reports.slice(0,128)),128)
for (const [v,s] of [[true,'是'],[false,'否'],[null,'—'],[undefined,'—'],[0,'—']])assert.equal(booleanResult(v),s)
assert.equal(blockedPacketCount(800),'800条');assert.equal(blockedPacketCount(false),'—')
assert.equal(legitimateHarmResult({legitimate_harm_bounded:true}),'—')
assert.equal(legitimateHarmResult({legitimate_harm_available:true,legitimate_harm_bounded:false}),'否')
assert.equal(legitimateHarmResult({legitimate_harm_available:true,legitimate_harm_bounded:true}),'是')
const read=n=>fs.readFileSync(new URL('../src/'+n,import.meta.url),'utf8')
assert(!read('views/OverviewView.vue').includes('历史点为'))
assert(!read('layouts/AppShell.vue').includes('footer'))
assert(!read('assets/main.css').includes('footer-note'))
assert(read('views/attacks/DosView.vue').includes('store.securityReports'))
assert(!read('views/attacks/DosView.vue').includes('不作为 Flooding 判定输入'))
assert(read('stores/simulation.ts').includes('securityReports.value = view.security_reports'))
